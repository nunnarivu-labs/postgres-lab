CREATE SCHEMA IF NOT EXISTS lab;

DO $$
BEGIN
  CREATE TYPE lab.order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled');
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
  CREATE DOMAIN lab.nonnegative_amount AS numeric(12, 2)
    CHECK (VALUE >= 0);
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
  CREATE TYPE lab.sample_composite AS (sample_number integer, label text);
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS lab.customers (
  customer_id bigint PRIMARY KEY,
  customer_uuid uuid NOT NULL,
  display_name varchar(80) NOT NULL,
  initials char(2) NOT NULL,
  email text NOT NULL,
  is_active boolean NOT NULL,
  birth_date date NOT NULL,
  signup_at timestamptz NOT NULL,
  last_seen_at timestamp,
  network inet NOT NULL,
  device_mac macaddr NOT NULL,
  preferences text[] NOT NULL,
  profile jsonb NOT NULL,
  CONSTRAINT customers_email_nonempty CHECK (length(email) > 0)
);

CREATE TABLE IF NOT EXISTS lab.products (
  product_id bigint PRIMARY KEY,
  sku text NOT NULL,
  name text NOT NULL,
  price lab.nonnegative_amount NOT NULL,
  approximate_weight real NOT NULL,
  scientific_measure double precision NOT NULL,
  category text NOT NULL,
  tags integer[] NOT NULL,
  content_hash bytea NOT NULL,
  stock_count integer NOT NULL CHECK (stock_count >= 0)
);

CREATE TABLE IF NOT EXISTS lab.orders (
  order_id bigint PRIMARY KEY,
  customer_id bigint NOT NULL,
  placed_at timestamptz NOT NULL,
  expected_ship_interval interval NOT NULL,
  status lab.order_status NOT NULL,
  total lab.nonnegative_amount NOT NULL,
  attributes json NOT NULL,
  source_ip cidr NOT NULL,
  order_number bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE IF NOT EXISTS lab.order_items (
  order_item_id bigint PRIMARY KEY,
  order_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity smallint NOT NULL CHECK (quantity > 0),
  unit_price numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
  line_total numeric(14, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED
);

CREATE TABLE IF NOT EXISTS lab.events (
  event_id bigint NOT NULL,
  customer_id bigint NOT NULL,
  occurred_at timestamptz NOT NULL,
  event_name text NOT NULL,
  payload jsonb NOT NULL,
  labels text[] NOT NULL,
  searchable tsvector NOT NULL,
  raw_sample bytea NOT NULL,
  PRIMARY KEY (event_id)
) PARTITION BY RANGE (event_id);

CREATE TABLE IF NOT EXISTS lab.events_1
  PARTITION OF lab.events FOR VALUES FROM (1) TO (50000001);
CREATE TABLE IF NOT EXISTS lab.events_2
  PARTITION OF lab.events FOR VALUES FROM (50000001) TO (100000001);

CREATE TABLE IF NOT EXISTS lab.measurements (
  measurement_id bigint NOT NULL,
  customer_id bigint NOT NULL,
  measured_at timestamptz NOT NULL,
  small_value smallint NOT NULL,
  integer_value integer NOT NULL,
  big_value bigint NOT NULL,
  exact_value numeric(18, 6) NOT NULL,
  point_value point NOT NULL,
  coverage int8range NOT NULL,
  address inet NOT NULL,
  PRIMARY KEY (measurement_id)
) PARTITION BY RANGE (measurement_id);

CREATE TABLE IF NOT EXISTS lab.measurements_1
  PARTITION OF lab.measurements FOR VALUES FROM (1) TO (50000001);
CREATE TABLE IF NOT EXISTS lab.measurements_2
  PARTITION OF lab.measurements FOR VALUES FROM (50000001) TO (100000001);

CREATE TABLE IF NOT EXISTS lab.documents (
  document_id bigint PRIMARY KEY,
  title text NOT NULL,
  body text NOT NULL,
  xml_metadata xml NOT NULL,
  json_metadata json NOT NULL,
  jsonb_metadata jsonb NOT NULL,
  search_vector tsvector NOT NULL,
  available_during tstzrange NOT NULL,
  flags bit varying(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS lab.type_playground (
  sample_id bigint PRIMARY KEY,
  integer_value integer NOT NULL,
  exact_value numeric(20, 4) NOT NULL,
  approximate_value double precision NOT NULL,
  bool_value boolean NOT NULL,
  time_value time NOT NULL,
  timestamp_value timestamp NOT NULL,
  timetz_value timetz NOT NULL,
  mac8_value macaddr8 NOT NULL,
  circle_value circle NOT NULL,
  polygon_value polygon NOT NULL,
  int_range int4range NOT NULL,
  int_multirange int4multirange NOT NULL,
  composite_value lab.sample_composite NOT NULL,
  enum_value lab.order_status NOT NULL,
  amount lab.nonnegative_amount NOT NULL,
  money_value money NOT NULL DEFAULT '0'::money
);
